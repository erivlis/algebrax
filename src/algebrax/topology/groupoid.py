"""
Simplicial Homotopy Path Groupoids.

Summary:
    Implements the fundamental path groupoid $\\Pi_1(K)$ of a simplicial complex $K$.
    Objects are vertices $v \\in K_0$, morphisms are edge paths $(v_0, v_1, \\dots, v_n)$,
    composition is path concatenation, inversion is path reversal, and homotopy
    equivalence ($\\sim$) is generated by 1-simplex backtracking cancellation
    $(u, v, u) \\sim (u,)$ and 2-simplex face moves $(u, v, w) \\sim (u, w)$
    whenever $\\{u, v, w\\} \\in K_2$.
"""

from __future__ import annotations

from collections import deque
from collections.abc import Iterable, Sequence
from typing import TYPE_CHECKING, Any

from algebrax.category.core import Groupoid

if TYPE_CHECKING:
    from algebrax.topology.homology import SimplicialComplex

PathMor = tuple[Any, ...]


class SimplicialPathGroupoid(Groupoid[Any, PathMor]):
    r"""Fundamental path groupoid $\Pi_1(K)$ over a simplicial complex $K$.

    Algebraic Laws (Up to Homotopy $\sim$, Diagrammatic Order `compose(f, g)` = $f ; g$):
        - Identity: $\mathrm{id}_v = (v,)$ with
          $\mathrm{compose}(\mathrm{id}_a, p) = p = \mathrm{compose}(p, \mathrm{id}_b)$.
        - Associativity:
          $\mathrm{compose}(\mathrm{compose}(p_1, p_2), p_3) = \mathrm{compose}(p_1, \mathrm{compose}(p_2, p_3))$.
        - Left/Right Inverses: $\mathrm{compose}(p, \mathrm{inv}(p)) \sim \mathrm{id}_{\mathrm{source}(p)}$ and
          $\mathrm{compose}(\mathrm{inv}(p), p) \sim \mathrm{id}_{\mathrm{target}(p)}$.
        - 2-Simplex Homotopy: If $\{u, v, w\} \in K_2$, then $(u, v, w) \sim (u, w)$.
    """

    def __init__(
        self,
        vertices: Iterable[Any],
        edges: Iterable[Sequence[Any]],
        triangles: Iterable[Sequence[Any]] = (),
    ) -> None:
        self.vertices: set[Any] = set(vertices)
        self.edges: set[frozenset[Any]] = set()
        self.adjacency: dict[Any, set[Any]] = {v: set() for v in self.vertices}

        for edge in edges:
            e_list = list(edge)
            if len(e_list) != 2:
                msg = f'Each edge must have 2 vertices, got {edge!r}'
                raise ValueError(msg)
            u, v = e_list[0], e_list[1]
            self.vertices.add(u)
            self.vertices.add(v)
            self.adjacency.setdefault(u, set()).add(v)
            self.adjacency.setdefault(v, set()).add(u)
            if u != v:
                self.edges.add(frozenset((u, v)))

        self.triangles: set[frozenset[Any]] = set()
        for tri in triangles:
            t_set = frozenset(tri)
            if len(t_set) != 3:
                msg = f'Each triangle must have 3 distinct vertices, got {tri!r}'
                raise ValueError(msg)
            self.triangles.add(t_set)
            t_list = list(t_set)
            for v in t_list:
                self.vertices.add(v)
                self.adjacency.setdefault(v, set())
            for i in range(3):
                for j in range(i + 1, 3):
                    u_i, v_j = t_list[i], t_list[j]
                    self.edges.add(frozenset((u_i, v_j)))
                    self.adjacency[u_i].add(v_j)
                    self.adjacency[v_j].add(u_i)

    @classmethod
    def from_simplicial_complex(cls, sc: SimplicialComplex) -> SimplicialPathGroupoid:
        r"""Construct $\Pi_1(K)$ directly from a `SimplicialComplex`."""
        vertices = [s[0] for s in sc._simplices.get(0, set())]
        edges = [tuple(s) for s in sc._simplices.get(1, set())]
        triangles = [tuple(s) for s in sc._simplices.get(2, set())]
        return cls(vertices=vertices, edges=edges, triangles=triangles)

    def id(self, x: Any) -> PathMor:
        r"""Identity path $(x,)$ at vertex $x$."""
        if x not in self.vertices:
            msg = f'Vertex {x!r} is not in the simplicial complex'
            raise ValueError(msg)
        return (x,)

    def source(self, f: PathMor) -> Any:
        r"""Starting vertex $v_0$ of path $(v_0, \dots, v_n)$."""
        if not f:
            msg = 'Path cannot be empty'
            raise ValueError(msg)
        return f[0]

    def target(self, f: PathMor) -> Any:
        r"""Ending vertex $v_n$ of path $(v_0, \dots, v_n)$."""
        if not f:
            msg = 'Path cannot be empty'
            raise ValueError(msg)
        return f[-1]

    def is_valid_path(self, path: PathMor) -> bool:
        r"""Return True if `path` is a non-empty valid walk in the 1-skeleton $K_1$."""
        if not path:
            return False
        if any(v not in self.vertices for v in path):
            return False
        for i in range(len(path) - 1):
            u, v = path[i], path[i + 1]
            if u != v and frozenset((u, v)) not in self.edges:
                return False
        return True

    def compose(self, f: PathMor, g: PathMor) -> PathMor:
        r"""Compose path $f: a \to b$ followed by $g: b \to c$ via concatenation.

        Follows diagrammatic composition order (`Category.compose(f, g)`): `f` is traversed first,
        then `g` starting from `f[-1] == g[0]`.
        """
        if not f or not g:
            msg = 'Cannot compose empty paths'
            raise ValueError(msg)
        if f[-1] != g[0]:
            msg = f'Path mismatch: target(f)={f[-1]!r} != source(g)={g[0]!r}'
            raise ValueError(msg)
        return f + g[1:]

    def inv(self, morphism: PathMor) -> PathMor:
        r"""Invert path $p = (v_0, \dots, v_n)$ to $p^{-1} = (v_n, \dots, v_0)$."""
        if not morphism:
            msg = 'Cannot invert an empty path'
            raise ValueError(msg)
        return morphism[::-1]

    @staticmethod
    def reduce_backtracking(path: PathMor) -> PathMor:
        r"""Iteratively cancel adjacent stammering $(u, u) \to (u,)$ and spurs $(u, v, u) \to (u,)$."""
        if not path:
            msg = 'Cannot reduce an empty path'
            raise ValueError(msg)
        stack: list[Any] = []
        for v in path:
            if stack and stack[-1] == v:
                continue
            if len(stack) >= 2 and stack[-2] == v:
                stack.pop()
            else:
                stack.append(v)
        return tuple(stack)

    def _elementary_neighbors(self, path: PathMor, max_length: int) -> list[PathMor]:
        r"""Generate 1-step homotopic neighbor paths via spur reduction and 2-simplex moves."""
        neighbors: list[PathMor] = []
        reduced = self.reduce_backtracking(path)
        if reduced != path:
            neighbors.append(reduced)

        n = len(path)
        # 1. Backtracking deletion: (..., u, v, u, ...) -> (..., u, ...)
        for i in range(n - 2):
            if path[i] == path[i + 2]:
                neighbors.append(path[: i + 1] + path[i + 3 :])

        # 2. 2-simplex shortcut: (..., u, v, w, ...) -> (..., u, w, ...) when {u, v, w} in K_2
        for i in range(n - 2):
            u, v, w = path[i], path[i + 1], path[i + 2]
            if frozenset((u, v, w)) in self.triangles:
                neighbors.append(path[: i + 1] + path[i + 2 :])

        # 3. 2-simplex expansion: (..., u, w, ...) -> (..., u, v, w, ...) when {u, v, w} in K_2
        if n < max_length:
            for i in range(n - 1):
                u, w = path[i], path[i + 1]
                for tri in self.triangles:
                    if u in tri and w in tri and u != w:
                        for v in tri:
                            if v != u and v != w:
                                neighbors.append((*path[: i + 1], v, *path[i + 1 :]))

        return neighbors

    def are_homotopic(
        self,
        path1: PathMor,
        path2: PathMor,
        *,
        max_visited: int = 2000,
    ) -> bool:
        r"""Test whether `path1` and `path2` are homotopic modulo 1-spurs and 2-faces.

        Args:
            path1: First vertex-tuple path.
            path2: Second vertex-tuple path.
            max_visited: Upper bound on BFS states explored.

        Returns:
            True if `path1` and `path2` share endpoints, are valid paths in $K_1$,
            and are connected by finite elementary homotopy moves.
        """
        if not self.is_valid_path(path1) or not self.is_valid_path(path2):
            return False
        if path1[0] != path2[0] or path1[-1] != path2[-1]:
            return False

        r1 = self.reduce_backtracking(path1)
        r2 = self.reduce_backtracking(path2)
        if r1 == r2:
            return True

        max_len = max(len(r1), len(r2)) + 3
        visited: set[PathMor] = {r1}
        queue: deque[PathMor] = deque([r1])

        while queue and len(visited) < max_visited:
            curr = queue.popleft()
            for nxt in self._elementary_neighbors(curr, max_len):
                nxt_red = self.reduce_backtracking(nxt)
                if nxt_red == r2 or nxt == r2:
                    return True
                for candidate in (nxt, nxt_red):
                    if candidate not in visited and len(visited) < max_visited:
                        visited.add(candidate)
                        queue.append(candidate)

        return False


__all__ = [
    'PathMor',
    'SimplicialPathGroupoid',
]
