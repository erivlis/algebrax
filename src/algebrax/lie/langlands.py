r"""
Langlands dual root systems, coroot bijections, and Iwahori-Hecke algebras.

Algebraic Signatures:
    Langlands Dual Cartan Matrix: $A^\vee = A^T$
    Coroot Inversion:             $\alpha^\vee = \frac{2\alpha}{\langle \alpha, \alpha \rangle} \in \Phi^\vee$
    Iwahori-Hecke Algebra:        $\mathcal{H}_q(W) = \langle T_1, \dots, T_r \mid
                                  (T_i - q)(T_i + 1) = 0, \text{ braid relations} \rangle$
"""

from __future__ import annotations

import math
from typing import TYPE_CHECKING

from algebrax.algebra._module import Algebra

if TYPE_CHECKING:
    from algebrax.lie.roots import RootSystem


def _dual_dynkin_label(dynkin_type: str) -> str:
    """Compute the canonical Dynkin label of the Langlands dual root system."""
    dt = dynkin_type.strip()
    if len(dt) >= 2 and dt[0] in ('B', 'C') and dt[1:].isdigit():
        dual_prefix = 'C' if dt[0] == 'B' else 'B'
        return f'{dual_prefix}{dt[1:]}'
    if dt in ('A1', 'B2', 'C2', 'G2', 'F4', 'E6', 'E7', 'E8') or (
            len(dt) >= 2 and dt[0] in ('A', 'D') and dt[1:].isdigit()
    ):
        return dt
    if dt.endswith('^v'):
        return dt[:-2]
    return f'{dt}^v'


def _compute_root_length_factors(cartan: list[list[int]]) -> list[int]:
    """Compute minimal positive integers q_i such that q_i * A_{ji} = q_j * A_{ij}.

    Here q_i = <alpha_i, alpha_i> / 2 represents the normalized squared length
    of the simple root alpha_i under the canonical Weyl-invariant bilinear form.
    """
    r = len(cartan)
    if r == 0:
        return []

    from fractions import Fraction

    q_frac: list[Fraction | None] = [None] * r
    for start in range(r):
        if q_frac[start] is not None:
            continue
        q_frac[start] = Fraction(1, 1)
        queue = [start]
        while queue:
            i = queue.pop(0)
            qi = q_frac[i]
            assert qi is not None
            for j in range(r):
                if cartan[i][j] != 0 and cartan[j][i] != 0 and q_frac[j] is None:
                    # Need q_i * A_{ji} == q_j * A_{ij}  =>  q_j = q_i * A_{ji} / A_{ij}
                    q_frac[j] = qi * Fraction(cartan[j][i], cartan[i][j])
                    queue.append(j)

    denoms = [f.denominator for f in q_frac if f is not None]
    lcm_den = 1
    for d in denoms:
        lcm_den = math.lcm(lcm_den, d)

    int_q = [int((f or Fraction(1, 1)) * lcm_den) for f in q_frac]
    common_gcd = math.gcd(*int_q) if int_q else 1
    return [x // common_gcd for x in int_q]


def langlands_dual_root_system(rs: RootSystem) -> RootSystem:
    r"""Construct the Langlands dual root system $\Phi^\vee$ via Cartan matrix transposition.

    Algebraic Signature:
        $\Phi \mapsto \Phi^\vee, \quad A^\vee = A^T, \quad B_r \longleftrightarrow C_r$

    Properties:
        - Involution: $(\Phi^\vee)^\vee = \Phi$ ($({A^T})^T = A$).
        - Swaps long and short roots, exchanging orthogonal $\mathfrak{so}_{2r+1}$ ($B_r$)
          and symplectic $\mathfrak{sp}_{2r}$ ($C_r$) root systems.
        - Preserves simply-laced root systems ($A_r, D_r, E_6, E_7, E_8$) identically.

    Args:
        rs: The primal crystallographic `RootSystem`.

    Returns:
        The Langlands dual `RootSystem` $\Phi^\vee$ generated by $A^T$.
    """
    from algebrax.lie.roots import RootSystem

    r = rs.rank
    dual_cartan = [[rs.cartan_matrix[j][i] for j in range(r)] for i in range(r)]
    dual_label = _dual_dynkin_label(rs.dynkin_type)
    return RootSystem.from_cartan_matrix(dual_cartan, dynkin_type=dual_label)


def root_inner_product(rs: RootSystem, alpha: tuple[int, ...], beta: tuple[int, ...]) -> int:
    r"""Compute the canonical Weyl-invariant integer bilinear form $\langle \alpha, \beta \rangle$.

    Normalized so that minimal-length roots satisfy $\langle \alpha_{\text{short}}, \alpha_{\text{short}} \rangle = 2$.
    Satisfies the crystallographic Cartan identity:
        $$\frac{2 \langle \alpha_j, \alpha_i \rangle}{\langle \alpha_i, \alpha_i \rangle} = A_{ji}$$
    """
    q = _compute_root_length_factors(rs.cartan_matrix)
    r = rs.rank
    total = 0
    for i in range(r):
        if alpha[i] == 0:
            continue
        for j in range(r):
            if beta[j] != 0:
                total += alpha[i] * q[i] * rs.cartan_matrix[j][i] * beta[j]
    return total


def coroot_in_dual(rs: RootSystem, root: tuple[int, ...]) -> tuple[int, ...]:
    r"""Map a root $\alpha \in \Phi$ to its coroot
    $\alpha^\vee = \frac{2\alpha}{\langle \alpha, \alpha \rangle} \in \Phi^\vee$.

    Expresses $\alpha^\vee$ in the simple coroot basis $(\alpha_1^\vee, \dots, \alpha_r^\vee)$
    of the Langlands dual root system $\Phi^\vee$.
    """
    q = _compute_root_length_factors(rs.cartan_matrix)
    norm_sq = root_inner_product(rs, root, root)
    if norm_sq <= 0:
        raise ValueError(f'Root {root} must have positive squared norm, got {norm_sq}.')
    q_alpha = norm_sq // 2
    return tuple((root[i] * q[i]) // q_alpha for i in range(rs.rank))


class IwahoriHeckeAlgebra(Algebra[float, dict[tuple[int, ...], float]]):
    r"""Iwahori-Hecke algebra $\mathcal{H}_q(W)$ of a crystallographic Weyl group $W$.

    Algebraic Signature:
        $\mathcal{H}_q(W) = \bigoplus_{w \in W} \mathbb{R} T_w, \quad (T_i - q)(T_i + 1) = 0$

    Carrier:
        `dict[tuple[int, ...], float]` — unboxed sparse linear combination of Weyl group elements,
        where each $w \in W$ is canonically keyed by its flattened $(r \times r)$ integer action
        matrix on the simple roots $(\alpha_1, \dots, \alpha_r)$.

    Multiplication Rules:
        For a simple reflection $s_i$ and basis element $T_w$:
        $$T_w \cdot T_{s_i} = \begin{cases}
            T_{w s_i} & \text{if } \ell(w s_i) > \ell(w) \iff w(\alpha_i) \in \Phi^+ \\
            (q - 1) T_w + q T_{w s_i} & \text{if } \ell(w s_i) < \ell(w) \iff w(\alpha_i) \in \Phi^-
        \end{cases}$$

    Properties:
        - Specializes at $q = 1$ to the classical Weyl group algebra $\mathbb{R}[W]$ ($T_i^2 = \mathbf{1}$).
        - Satisfies the quadratic Hecke relation $T_i^2 = (q - 1) T_i + q \mathbf{1}$.
        - Satisfies the Coxeter braid relations
          $\underbrace{T_i T_j T_i \cdots}_{m_{ij}} = \underbrace{T_j T_i T_j \cdots}_{m_{ij}}$.
    """

    def __init__(self, root_system: RootSystem, q: float = 1.0, tol: float = 1e-12) -> None:
        self._rs = root_system
        self._q = float(q)
        self._tol = tol
        r = root_system.rank
        self._rank = r
        self._id_key: tuple[int, ...] = tuple(1 if i == j else 0 for i in range(r) for j in range(r))

    @property
    def root_system(self) -> RootSystem:
        """Underlying crystallographic root system."""
        return self._rs

    @property
    def q(self) -> float:
        """Hecke deformation parameter $q$."""
        return self._q

    @property
    def zero(self) -> dict[tuple[int, ...], float]:
        """Additive zero element."""
        return {}

    @property
    def one(self) -> dict[tuple[int, ...], float]:
        """Multiplicative identity $T_e$."""
        return {self._id_key: 1.0}

    def is_zero(self, a: dict[tuple[int, ...], float]) -> bool:
        """Check whether an element is zero within tolerance."""
        return all(abs(v) <= self._tol for v in a.values())

    def generator(self, i: int) -> dict[tuple[int, ...], float]:
        r"""Return the $i$-th simple reflection generator $T_i = T_{s_i}$ ($0 \le i < r$)."""
        if not (0 <= i < self._rank):
            raise IndexError(f'Generator index {i} out of bounds for rank {self._rank}.')
        s_i_key = self._apply_right_reflection(self._id_key, i)
        return {s_i_key: 1.0}

    def _apply_right_reflection(self, w_key: tuple[int, ...], i: int) -> tuple[int, ...]:
        """Compute the matrix key for w * s_i.

        In w_key, row j (w_key[j*r : (j+1)*r]) is w(alpha_j) in simple root coordinates.
        Since s_i(alpha_j) = alpha_j - A_{ji} alpha_i, by linearity:
            (w s_i)(alpha_j) = w(alpha_j) - A_{ji} w(alpha_i).
        """
        r = self._rank
        c_mat = self._rs.cartan_matrix
        out = list(w_key)
        w_alpha_i = w_key[i * r: (i + 1) * r]
        for j in range(r):
            a_ji = c_mat[j][i]
            if a_ji != 0:
                base = j * r
                for k in range(r):
                    out[base + k] -= a_ji * w_alpha_i[k]
        return tuple(out)

    def _is_length_increasing(self, w_key: tuple[int, ...], i: int) -> bool:
        """Return True iff l(w s_i) > l(w), which holds iff w(alpha_i) is a positive root."""
        r = self._rank
        w_alpha_i = w_key[i * r: (i + 1) * r]
        return all(c >= 0 for c in w_alpha_i) and any(c > 0 for c in w_alpha_i)

    def coxeter_length(self, w_key: tuple[int, ...]) -> int:
        r"""Compute the Coxeter length $\ell(w) = |\{\alpha \in \Phi^+ \mid w(\alpha) \in \Phi^-\}|$."""
        r = self._rank
        count = 0
        for pos_root in self._rs.positive_roots:
            # Compute w(pos_root) = sum_j pos_root[j] * w(alpha_j)
            img = [0] * r
            for j, c_j in enumerate(pos_root):
                if c_j != 0:
                    base = j * r
                    for k in range(r):
                        img[k] += c_j * w_key[base + k]
            if any(c < 0 for c in img):
                count += 1
        return count

    def _reduced_word(self, w_key: tuple[int, ...]) -> list[int]:
        """Decompose a Weyl group element w into a reduced word [i_1, ..., i_k] of simple reflections."""
        word: list[int] = []
        curr = w_key
        while curr != self._id_key:
            # Find i such that l(curr * s_i) < l(curr), i.e., curr(alpha_i) < 0
            found = False
            for i in range(self._rank):
                if not self._is_length_increasing(curr, i):
                    curr = self._apply_right_reflection(curr, i)
                    word.append(i)
                    found = True
                    break
            if not found:
                raise RuntimeError('Failed to reduce Weyl group element to identity.')
        word.reverse()
        return word

    def add(
            self,
            a: dict[tuple[int, ...], float],
            b: dict[tuple[int, ...], float],
    ) -> dict[tuple[int, ...], float]:
        """Linear combination addition."""
        res = dict(a)
        for k, v in b.items():
            nv = res.get(k, 0.0) + v
            if abs(nv) <= self._tol:
                res.pop(k, None)
            else:
                res[k] = nv
        return res

    def neg(self, a: dict[tuple[int, ...], float]) -> dict[tuple[int, ...], float]:
        """Additive negation."""
        return {k: -v for k, v in a.items() if abs(v) > self._tol}

    def sub(
            self,
            a: dict[tuple[int, ...], float],
            b: dict[tuple[int, ...], float],
    ) -> dict[tuple[int, ...], float]:
        """Difference $a - b$."""
        return self.add(a, self.neg(b))

    def scale(self, r: float, a: dict[tuple[int, ...], float]) -> dict[tuple[int, ...], float]:
        r"""Scalar multiplication $r \cdot a$."""
        if abs(r) <= self._tol:
            return {}
        return {k: r * v for k, v in a.items() if abs(r * v) > self._tol}

    def smul(self, r: float, a: dict[tuple[int, ...], float]) -> dict[tuple[int, ...], float]:
        """Alias for scalar multiplication."""
        return self.scale(r, a)

    def _mul_basis_by_generator(
            self,
            elem: dict[tuple[int, ...], float],
            i: int,
    ) -> dict[tuple[int, ...], float]:
        """Right-multiply an algebra element by simple generator T_i."""
        out: dict[tuple[int, ...], float] = {}
        q = self._q
        q_minus_1 = q - 1.0
        for w_key, coeff in elem.items():
            ws_key = self._apply_right_reflection(w_key, i)
            if self._is_length_increasing(w_key, i):
                out[ws_key] = out.get(ws_key, 0.0) + coeff
            else:
                if abs(q_minus_1) > self._tol:
                    out[w_key] = out.get(w_key, 0.0) + coeff * q_minus_1
                if abs(q) > self._tol:
                    out[ws_key] = out.get(ws_key, 0.0) + coeff * q
        return {k: v for k, v in out.items() if abs(v) > self._tol}

    def mul(
            self,
            a: dict[tuple[int, ...], float],
            b: dict[tuple[int, ...], float],
    ) -> dict[tuple[int, ...], float]:
        r"""Multiply two elements in the Iwahori-Hecke algebra $\mathcal{H}_q(W)$."""
        if not a or not b:
            return {}
        total: dict[tuple[int, ...], float] = {}
        for w_b, coeff_b in b.items():
            if abs(coeff_b) <= self._tol:
                continue
            word = self._reduced_word(w_b)
            term = dict(a)
            for gen_idx in word:
                term = self._mul_basis_by_generator(term, gen_idx)
            total = self.add(total, self.scale(coeff_b, term))
        return total


