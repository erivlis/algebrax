r"""
Algebraic and higher K-theory ($K_0, K_1, K_2^M$), Serre-Swan bundles, and Schubert cohomology rings.

Bridges affine algebraic varieties across the algebraic K-theory tower:
- $K_0$: Serre-Swan projective bundle idempotents (`is_serre_swan_projective_bundle`),
  Borel's Schubert/Chern cohomology ring $H^*(\operatorname{Gr}(k, n); k)$
  (`schubert_chern_cohomology_ring`), and motivic $\mathbb{F}_p$-point counting
  on $K_0(\mathbf{Var}_{\mathbb{F}_p})$ (`motivic_point_count_homomorphism`).
- $K_1$: Unit invertibility in $k[V]^\times \hookrightarrow K_1(k[V])$ via Rabinowitsch
  tag-variable ideals (`coordinate_ring_unit_inverse`).
- $K_2^M$: The $p$-adic Tame Symbol $T_p: K_2(\mathbb{Q}) \to \mathbb{F}_p^\times$
  (`tame_symbol_padic`) and Milnor-Voevodsky norm-residue conic varieties
  $a x^2 + b y^2 = 1$ (`milnor_symbol_conic_variety`).
"""

from __future__ import annotations

from fractions import Fraction
from typing import TypeVar

from algebrax.algebra import (
    CommQuotientRing,
    Field,
    GroebnerIdeal,
    MultivariatePolynomialAlgebra,
    PAdicField,
    SparseMPoly,
    groebner_basis,
)
from algebrax.matrix import dot as matrix_dot
from algebrax.typing import SparseMatrix
from algebrax.variety.affine import AffineVariety, _fields_compatible
from algebrax.variety.finite import enum_variety_points

V = TypeVar('V')


def is_serre_swan_projective_bundle(
    variety: AffineVariety[V],
    projector_matrix: SparseMatrix[int, SparseMPoly[V]],
) -> bool:
    r"""Verify the Serre-Swan $K_0(V)$ condition $P^2 \equiv P \pmod{I(V)}$ for an algebraic vector bundle.

    An idempotent matrix $P \in M_r(k[V])$ over `variety.coordinate_ring` defines a finitely
    generated projective $k[V]$-module $\operatorname{im}(P)$, corresponding to an algebraic
    vector bundle $E \to V$ in $K_0(V)$.

    Args:
        variety: Base affine variety $V$.
        projector_matrix: Sparse matrix of polynomials $P \in M_r(k[V])$ with non-negative integer indices.

    Returns:
        True iff $P^2 \equiv P \pmod{I(V)}$.

    Raises:
        ValueError: If row/column indices are negative or a polynomial has wrong monomial arity.
    """
    coord_ring = variety.coordinate_ring
    reduce_poly = variety.ideal.reduce
    n = variety.ambient_dimension

    normalized: dict[int, dict[int, SparseMPoly[V]]] = {}
    for row_idx, cols in projector_matrix.items():
        if isinstance(row_idx, bool) or not isinstance(row_idx, int) or row_idx < 0:
            raise ValueError(f'Projector row index must be a non-negative integer, got {row_idx!r}.')
        clean_row: dict[int, SparseMPoly[V]] = {}
        for col_idx, poly in cols.items():
            if isinstance(col_idx, bool) or not isinstance(col_idx, int) or col_idx < 0:
                raise ValueError(f'Projector column index must be a non-negative integer, got {col_idx!r}.')
            for mon in poly:
                if len(mon) != n:
                    raise ValueError(
                        f'Entry ({row_idx}, {col_idx}) monomial {mon!r} has arity {len(mon)}, expected {n}.'
                    )
            red = reduce_poly(poly)
            if red:
                clean_row[col_idx] = red
        if clean_row:
            normalized[row_idx] = clean_row

    squared = matrix_dot(normalized, normalized, semiring=coord_ring)
    return squared == normalized


def schubert_chern_cohomology_ring(
    field: Field[V],
    k_subspace: int,
    n_ambient: int,
) -> CommQuotientRing[SparseMPoly[V]]:
    r"""Construct Borel's Chern/Schubert cohomology quotient ring $H^*(\operatorname{Gr}(k, n); k)$.

    Generated by tautological Chern classes $c_1, \dots, c_k$ (variables $0 \dots k-1$) and
    quotient Chern classes $\tilde{c}_1, \dots, \tilde{c}_{n-k}$ (variables $k \dots n-1$)
    modulo the Whitney sum relation:
    $$(1 + c_1 t + \cdots + c_k t^k)(1 + \tilde{c}_1 t + \cdots + \tilde{c}_{n-k} t^{n-k}) = 1$$

    As a $k$-vector space, $\dim_k H^*(\operatorname{Gr}(k, n); k) = \binom{n}{k}$.

    Args:
        field: Exact coefficient field $k$.
        k_subspace: Subspace dimension $k$ ($1 \le k < n$).
        n_ambient: Ambient vector-space dimension $n$.

    Raises:
        ValueError: If `not (1 <= k_subspace < n_ambient)`.
    """
    if not (1 <= k_subspace < n_ambient):
        raise ValueError(
            f'Grassmannian Gr(k, n) requires 1 <= k < n, got k={k_subspace}, n={n_ambient}.'
        )
    q = n_ambient - k_subspace
    ring = MultivariatePolynomialAlgebra(field, n_ambient, order='grevlex')

    c_classes: list[SparseMPoly[V]] = [ring.one, *(ring.gen(i) for i in range(k_subspace))]
    q_classes: list[SparseMPoly[V]] = [ring.one, *(ring.gen(k_subspace + j) for j in range(q))]

    whitney_rels: list[SparseMPoly[V]] = []
    for deg in range(1, n_ambient + 1):
        rel: SparseMPoly[V] = ring.zero
        for i in range(max(0, deg - q), min(k_subspace, deg) + 1):
            j = deg - i
            rel = ring.add(rel, ring.mul(c_classes[i], q_classes[j]))
        whitney_rels.append(rel)

    ideal = GroebnerIdeal(ring, whitney_rels)
    return CommQuotientRing(ring, ideal)


def motivic_point_count_homomorphism(
    variety_pair: tuple[AffineVariety[V], AffineVariety[V]],
) -> int:
    r"""Evaluate the $\mathbb{F}_q$-point counting homomorphism $\#V(\mathbb{F}_q) - \#W(\mathbb{F}_q)$
    on formal difference classes $[V] - [W] \in K_0(\mathbf{Var}_{\mathbb{F}_q})$.

    Satisfies cut-and-paste scissor congruence $[V] = [Z] + [V \setminus Z]$ in `GrothendieckRing`.

    Args:
        variety_pair: Pair `(v_pos, v_neg)` of finite-field varieties over the same finite field.

    Raises:
        TypeError: If the two varieties do not share the same compatible finite field.
    """
    v_pos, v_neg = variety_pair
    if not _fields_compatible(v_pos.ring.field, v_neg.ring.field):
        raise TypeError(
            f'Incompatible finite fields in motivic difference class: '
            f'{v_pos.ring.field!r} vs {v_neg.ring.field!r}.'
        )
    return len(enum_variety_points(v_pos)) - len(enum_variety_points(v_neg))


def coordinate_ring_unit_inverse(
    variety: AffineVariety[V],
    poly: SparseMPoly[V],
) -> SparseMPoly[V] | None:
    r"""Test whether `poly` is a unit $[u] \in k[V]^\times \hookrightarrow K_1(k[V])$ and return $u^{-1} \bmod I(V)$.

    Checks $1 \in \langle I(V), u \rangle$ (exact invertibility criterion in $k[X]/I$), then extracts
    the unique canonical inverse $u^{-1} \bmod I(V)$ via the auxiliary tag-variable ideal
    $\langle I(V),\, t \cdot u - 1 \rangle$ under lexicographic order $t > x_1 > \dots > x_n$.

    Args:
        variety: Affine variety $V$.
        poly: Polynomial $u \in k[X]$ representing a class in $k[V]$.

    Returns:
        Canonical inverse polynomial in `variety.coordinate_ring`, or `None` if `poly` is not a unit.
    """
    if variety.is_empty_over_closure():
        return {}

    u = variety.ideal.reduce(poly)
    if not u:
        return None

    # O(1) fast path for non-zero constant polynomials
    zero_key = variety.ring.zero_key
    if len(u) == 1 and zero_key in u:
        return {zero_key: variety.ring.field.inv(u[zero_key])}

    # Exact invertibility check: u is a unit in k[X]/I iff 1 in <I, u>
    aug_ideal = GroebnerIdeal(variety.ring, [*variety.ideal.basis, u])
    if not aug_ideal.is_unit():
        return None

    n = variety.ambient_dimension
    ext_ring = MultivariatePolynomialAlgebra(variety.ring.field, n + 1, order='lex')
    t = ext_ring.gen(0)
    u_lifted = {(0, *m): c for m, c in u.items()}
    ext_gens: list[SparseMPoly[V]] = [
        {(0, *m): c for m, c in g.items()} for g in variety.ideal.basis
    ]
    ext_gens.append(ext_ring.sub(ext_ring.mul(t, u_lifted), ext_ring.one))

    gb = groebner_basis(ext_ring, ext_gens)
    t_mon = (1, *(0,) * n)
    for g in gb:
        if ext_ring.lm(g) == t_mon:
            # g = t - v(x) (monic in t) => inverse is -tail
            tail = {m[1:]: variety.ring.field.neg(c) for m, c in g.items() if m != t_mon}
            inv_poly = variety.ideal.reduce(tail)
            if variety.coordinate_ring.mul(u, inv_poly) == variety.coordinate_ring.one:
                return inv_poly

    return None


def _exact_padic_split(q: Fraction, prime: int) -> tuple[int, Fraction]:
    """Factor a non-zero rational q = prime^v * u with gcd(num(u), p) = gcd(den(u), p) = 1."""
    num = q.numerator
    den = q.denominator
    v = 0
    while num % prime == 0:
        num //= prime
        v += 1
    while den % prime == 0:
        den //= prime
        v -= 1
    return v, Fraction(num, den)


def tame_symbol_padic(
    a: int | Fraction,
    b: int | Fraction,
    prime: int,
) -> int:
    r"""Evaluate the $K_2(\mathbb{Q}) \to \mathbb{F}_p^\times$ Tame Symbol:
    $$T_p(a, b) = (-1)^{v_p(a) v_p(b)} \frac{a^{v_p(b)}}{b^{v_p(a)}} \pmod p \in \{1, \dots, p - 1\}$$

    Uses `PAdicField(prime)` for prime validation before extracting exact $p$-adic valuations.
    Satisfies Matsumoto's Steinberg relation $T_p(a, 1 - a) \equiv 1 \pmod p$ for all $a \notin \{0, 1\}$.

    Args:
        a: Non-zero rational number.
        b: Non-zero rational number.
        prime: Prime integer $p \ge 2$.

    Returns:
        Residue in $\{1, \dots, p - 1\} \cong \mathbb{F}_p^\times$.

    Raises:
        TypeError: If `prime` is not an integer (or is a `bool`).
        ValueError: If `prime` is not prime or either `a` or `b` is zero.
    """
    if isinstance(prime, bool) or not isinstance(prime, int):
        raise TypeError(f'prime must be a prime integer >= 2, got {prime!r}.')
    # Validate primality via PAdicField BEFORE dividing by prime
    PAdicField(prime, precision=4)

    fa = Fraction(a)
    fb = Fraction(b)
    if fa == 0 or fb == 0:
        raise ValueError('Tame symbol T_p(a, b) requires non-zero rational arguments a and b.')

    va, ua = _exact_padic_split(fa, prime)
    vb, ub = _exact_padic_split(fb, prime)

    ua_mod = (ua.numerator * pow(ua.denominator % prime, -1, prime)) % prime
    ub_mod = (ub.numerator * pow(ub.denominator % prime, -1, prime)) % prime

    sign = -1 if (va * vb) % 2 != 0 else 1
    num_term = pow(ua_mod, vb, prime) if vb >= 0 else pow(pow(ua_mod, -1, prime), -vb, prime)
    den_term = pow(ub_mod, -va, prime) if va <= 0 else pow(pow(ub_mod, -1, prime), va, prime)
    return (sign * num_term * den_term) % prime


def milnor_symbol_conic_variety(
    ring: MultivariatePolynomialAlgebra[V],
    a: V,
    b: V,
) -> AffineVariety[V]:
    r"""Construct the norm-residue conic variety $a x^2 + b y^2 - 1 = 0$ witnessing $\{a, b\} \in K_2^M(k)/2$.

    By the Milnor-Voevodsky Norm Residue Theorem (for $\operatorname{char}(k) \ne 2$), the mod-2
    Milnor K-theory symbol $\{a, b\}$ (and its quaternion / 2-generator Clifford algebra
    $\mathrm{Cl}_{a,b}(k)$) splits iff this conic has a $k$-rational point (immediately satisfied
    by $(1, 1)$ when $b = 1 - a$, geometrically witnessing the Steinberg relation $\{a, 1 - a\} = 0$).

    Args:
        ring: A 2-variable polynomial ring $k[x, y]$.
        a: Non-zero field element $a \in k^\times$.
        b: Non-zero field element $b \in k^\times$.

    Raises:
        ValueError: If `ring.n_vars != 2` or either `a` or `b` is zero in `ring.field`.
    """
    if ring.n_vars != 2:
        raise ValueError(f'milnor_symbol_conic_variety requires a 2-variable ring, got n_vars={ring.n_vars}.')
    if ring.field.is_zero(a) or ring.field.is_zero(b):
        raise ValueError('Milnor symbol conic a*x^2 + b*y^2 = 1 requires non-zero field elements a and b.')
    poly = ring.clean(
        {
            (2, 0): a,
            (0, 2): b,
            (0, 0): ring.field.neg(ring.field.one),
        }
    )
    return AffineVariety(ring, [poly])


