r"""
Reproducing Kernel Hilbert Spaces (RKHS), Mercer kernels, Gram matrices, and kernel ridge regression.

Mathematical Foundations:
    - Mercer's Theorem: Any positive semi-definite continuous kernel $k(x, y)$ implicitly defines an inner
      product in a Hilbert feature space $\mathcal{H}$: $k(x, y) = \langle \Phi(x), \Phi(y) \rangle_{\mathcal{H}}$.
    - Gram Matrix: $K_{ij} = k(x_i, x_j)$ is symmetric positive semi-definite.
    - Reproducing Property: $f(x) = \langle f, k(\cdot, x) \rangle_{\mathcal{H}}$ for all $f \in \mathcal{H}$.
"""

from __future__ import annotations

import math
from collections.abc import Callable, Sequence
from typing import Any

from algebrax.analysis.normed import inner_euclidean, norm_p
from algebrax.matrix.decompose import solve
from algebrax.typing import SparseMatrix, SparseVector


def linear_kernel(u: SparseVector[Any, float], v: SparseVector[Any, float]) -> float:
    r"""Linear Mercer kernel: $k(u, v) = \langle u, v \rangle$."""
    return float(inner_euclidean(u, v))


def polynomial_kernel(
    u: SparseVector[Any, float],
    v: SparseVector[Any, float],
    degree: float = 2.0,
    c: float = 1.0,
) -> float:
    r"""Polynomial Mercer kernel: $k(u, v) = (\langle u, v \rangle + c)^d$ ($c \ge 0, d \ge 1$)."""
    dot = float(inner_euclidean(u, v))
    return math.pow(dot + c, degree)


def rbf_kernel(
    u: SparseVector[Any, float],
    v: SparseVector[Any, float],
    gamma: float = 1.0,
) -> float:
    r"""Radial Basis Function (RBF / Gaussian) kernel: $k(u, v) = \exp(-\gamma \|u - v\|_2^2)$."""
    diff: dict[Any, float] = dict(u)
    for k, val in v.items():
        diff[k] = diff.get(k, 0.0) - val
    dist_sq = sum(val * val for val in diff.values())
    return math.exp(-gamma * dist_sq)


def cosine_kernel(u: SparseVector[Any, float], v: SparseVector[Any, float]) -> float:
    r"""Cosine Mercer kernel: $k(u, v) = \frac{\langle u, v \rangle}{\|u\|_2 \|v\|_2}$."""
    norm_u = norm_p(u, 2.0)
    norm_v = norm_p(v, 2.0)
    if norm_u < 1e-15 or norm_v < 1e-15:
        return 0.0
    return float(inner_euclidean(u, v)) / (norm_u * norm_v)


class ReproducingKernelHilbertSpace:
    r"""Reproducing Kernel Hilbert Space (RKHS) generated by a positive-definite Mercer kernel.

    Parameters:
        kernel_fn: Mercer kernel $k : \mathcal{X} \times \mathcal{X} \to \mathbb{R}$.
    """

    def __init__(self, kernel_fn: Callable[[Any, Any], float]) -> None:
        self.kernel_fn = kernel_fn

    def __call__(self, u: Any, v: Any) -> float:
        r"""Evaluate kernel inner product $k(u, v) = \langle \Phi(u), \Phi(v) \rangle$."""
        return self.kernel_fn(u, v)

    def distance(self, u: Any, v: Any) -> float:
        r"""Compute induced metric distance in feature space:
        $$d_{\mathcal{H}}(u, v) = \|\Phi(u) - \Phi(v)\|_{\mathcal{H}} = \sqrt{k(u, u) - 2k(u, v) + k(v, v)}$$
        """
        val = self.kernel_fn(u, u) - 2.0 * self.kernel_fn(u, v) + self.kernel_fn(v, v)
        return math.sqrt(max(0.0, val))

    def build_gram_matrix(
        self,
        samples: Sequence[Any],
        tol: float = 1e-12,
    ) -> SparseMatrix[int, float]:
        r"""Assemble the sparse positive semi-definite Gram matrix $K_{ij} = k(x_i, x_j)$.

        Complexity:
            Time $O(N^2 \cdot \operatorname{cost}(k))$, Space $O(\operatorname{nnz}(K))$.
        """
        n = len(samples)
        gram: SparseMatrix[int, float] = {}

        for i in range(n):
            for j in range(i, n):
                val = self.kernel_fn(samples[i], samples[j])
                if abs(val) > tol:
                    gram.setdefault(i, {})[j] = val
                    if i != j:
                        gram.setdefault(j, {})[i] = val

        return gram

    def kernel_ridge_regression(
        self,
        train_x: Sequence[Any],
        train_y: Sequence[float],
        alpha: float = 1e-4,
    ) -> Callable[[Any], float]:
        r"""Fit a kernel ridge regression model: $(K + \alpha I) w = y$.

        Returns a prediction function $f(x) = \sum_{i=1}^N w_i k(x_i, x)$.
        """
        n = len(train_x)
        if len(train_y) != n:
            raise ValueError(f'Dimension mismatch: len(train_x)={n} != len(train_y)={len(train_y)}')

        # Build regularized Gram matrix (K + alpha * I)
        gram = self.build_gram_matrix(train_x)
        reg_gram: SparseMatrix[int, float] = {}
        for i in range(n):
            reg_gram[i] = dict(gram.get(i, {}))
            reg_gram[i][i] = reg_gram[i].get(i, 0.0) + alpha

        # Right-hand side vector y
        rhs = {i: float(train_y[i]) for i in range(n) if train_y[i] != 0.0}

        # Solve for dual weights w
        w_sparse = solve(reg_gram, rhs)
        weights = [w_sparse.get(i, 0.0) for i in range(n)]

        def predictor(x: Any) -> float:
            return sum(
                w * self.kernel_fn(train_x[i], x)
                for i, w in enumerate(weights)
                if abs(w) > 1e-12
            )

        return predictor
