class IntegerModuloIdeal(PrincipalIdeal[int]):
    r"""The principal ideal $(n) = n\mathbb{Z}$ in the ring of integers $\mathbb{Z}$.

    Canonical coset representatives are standard least non-negative residues $\{0, 1, \dots, n - 1\}$.
    """

    def __init__(self, modulus: int) -> None:
        if modulus <= 0:
            raise ValueError(f'Modulus must be positive, got {modulus}')
        self.modulus = modulus

    @property
    def generator(self) -> int:
        return self.modulus

    def contains(self, element: int) -> bool:
        return (element % self.modulus) == 0

    def reduce(self, element: int) -> int:
        return element % self.modulus

    def __contains__(self, element: int) -> bool:
        return self.contains(element)


class NilpotentIdeal(PrincipalIdeal[int | dict[int, T]]):
    r"""The nilpotent ideal $(\varepsilon^k)$ of infinitesimal order $k$ in $\mathbb{R}[\varepsilon]$.

    Supports both integer degree exponents ($d \ge k$) and sparse univariate polynomial dicts
    (`dict[int, T]`), annihilating all monomials of degree $\ge k$.
    """

    def __init__(self, nilpotency_degree: int = 2) -> None:
        if nilpotency_degree <= 0:
            raise ValueError(f'Nilpotency degree must be positive, got {nilpotency_degree}')
        self.nilpotency_degree = nilpotency_degree

    @property
    def generator(self) -> int:
        return self.nilpotency_degree

    def contains(self, element: int | dict[int, T]) -> bool:
        if isinstance(element, int):
            return element >= self.nilpotency_degree
        return all(deg >= self.nilpotency_degree for deg, coeff in element.items() if coeff != 0)

    def reduce(self, element: int | dict[int, T]) -> int | dict[int, T] | None:
        if isinstance(element, int):
            return None if element >= self.nilpotency_degree else element
        return {deg: coeff for deg, coeff in element.items() if deg < self.nilpotency_degree and coeff != 0}

    def __contains__(self, element: int | dict[int, T]) -> bool:
        return self.contains(element)


class PolynomialTruncationIdeal(PrincipalIdeal[dict[int, T]], Generic[T]):
    r"""The principal monomial ideal $(x^n)$ in the polynomial ring $R[x]$, truncating degrees $\ge n$.

    Carrier:
        `dict[int, T]` (Sparse mapping from degree $d \in \mathbb{N}_0$ to coefficient $c_d \in R$).
    """

    def __init__(self, max_degree: int, zero_coeff: T = 0) -> None:  # type: ignore[assignment]
        if max_degree <= 0:
            raise ValueError(f'Maximum truncation degree must be positive, got {max_degree}')
        self.max_degree = max_degree
        self.zero_coeff = zero_coeff

    @property
    def generator(self) -> dict[int, T]:
        return {self.max_degree: type(self.zero_coeff)(1)}  # type: ignore[call-arg]

    def contains(self, poly: dict[int, T]) -> bool:
        return all(deg >= self.max_degree for deg, coeff in poly.items() if coeff != self.zero_coeff)

    def reduce(self, poly: dict[int, T]) -> dict[int, T]:
        return {
            deg: coeff
            for deg, coeff in poly.items()
            if deg < self.max_degree and coeff != self.zero_coeff
        }

    def quotient_term(self, deg: int, coeff: T) -> list[tuple[int, T]]:
        r""" Term reducer compatible with `QuotientMonoidAlgebraSemiring(quotient_fn=...)`."""
        if deg >= self.max_degree or coeff == self.zero_coeff:
            return []
        return [(deg, coeff)]

    def __contains__(self, poly: dict[int, T]) -> bool:
        return self.contains(poly)


class KernelIdeal(Ideal[Dom], Generic[Dom, Cod]):
    r"""The kernel ideal $\ker \phi = \{x \in R_1 \mid \phi(x) = \mathbf{0}_{R_2}\}$ of $\phi: R_1 \to R_2$.

    Realizes the First Isomorphism Theorem ($R_1 / \ker \phi \cong \operatorname{im} \phi$):
    two elements $a, b \in R_1$ belong to the same coset modulo $\ker \phi$ if and only if
    $\phi(a) = \phi(b)$.
    """

    def __init__(
        self,
        hom: Homomorphism[Dom, Cod],
        cod_ring: HasZero[Cod],
        reducer: Callable[[Dom], Dom],
        tol: float = 1e-9,
    ) -> None:
        self.hom = hom
        self.cod_ring = cod_ring
        self._reducer = reducer
        self.tol = tol

    def contains(self, element: Dom) -> bool:
        return _elements_equal(self.hom(element), self.cod_ring.zero, self.tol)

    def reduce(self, element: Dom) -> Dom:
        return self._reducer(element)

    def __contains__(self, element: Dom) -> bool:
        return self.contains(element)


class SubspaceLieIdeal(LieIdeal[dict[K, T]], Generic[K, T]):
    r"""A Lie ideal $\mathfrak{i} \triangleleft \mathfrak{g}$ spanned by a subset of basis keys $S \subseteq K$.

    For sparse vector elements `dict[K, T]`, an element belongs to $\mathfrak{i}$ iff all its
    non-zero basis keys lie in `ideal_keys`, and reduction modulo $\mathfrak{i}$ projects onto
    the complementary basis keys $K \setminus S$.
    """

    def __init__(self, ideal_keys: set[K] | frozenset[K], zero_coeff: T = 0) -> None:  # type: ignore[assignment]
        self.ideal_keys = frozenset(ideal_keys)
        self.zero_coeff = zero_coeff

    def contains(self, element: dict[K, T]) -> bool:
        return all(k in self.ideal_keys for k, v in element.items() if v != self.zero_coeff)

    def reduce(self, element: dict[K, T]) -> dict[K, T]:
        return {k: v for k, v in element.items() if k not in self.ideal_keys and v != self.zero_coeff}

    def __contains__(self, element: dict[K, T]) -> bool:
        return self.contains(element)


