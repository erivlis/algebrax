def _elements_equal(a: Any, b: Any, tol: float) -> bool:
    if a == b:
        return True
    if isinstance(a, float) and isinstance(b, float):
        return math.isclose(a, b, rel_tol=tol, abs_tol=tol)
    if isinstance(a, complex) and isinstance(b, complex):
        return cmath.isclose(a, b, rel_tol=tol, abs_tol=tol)
    return False


@runtime_checkable
class Ideal(HasContains[V], HasReduce[V], Protocol):
    r"""A two-sided mathematical ideal $I \triangleleft R$.

    Algebraic Signature:
        $\langle V, \operatorname{contains}, \operatorname{reduce} \rangle$

    An ideal is an additive subgroup $(I, +, \mathbf{0}, -)$ that absorbs multiplication by
    arbitrary elements of the ambient ring $R$:
    $$\forall x \in I, \; \forall r \in R: \quad r \cdot x \in I \quad \text{and} \quad x \cdot r \in I$$

    To support zero-overhead, unboxed quotient arithmetic in $R / I$, an `Ideal[V]`
    provides both a membership predicate `contains(x)` (`HasContains[V]`) and a canonical coset
    representative normal-form reducer `reduce(x)` (`HasReduce[V]`) satisfying:
    $$x - y \in I \iff \mathrm{reduce}(x) == \mathrm{reduce}(y)$$
    $$\text{and} \quad x \in I \iff \mathrm{reduce}(x) == \mathrm{reduce}(\mathbf{0}_R)$$
    """

