r"""
Mathematical ideals and canonical normal form reducers for rings, polynomials, and Lie algebras.

Algebraic Signatures (EP-0201 / EP-0150 AMDS):
    Ideal:          $I \triangleleft R \; (\forall x, y \in I, r \in R: x - y \in I, r \cdot x \in I, x \cdot r \in I)$
    PrincipalIdeal: $I = (a) = aR$
    LieIdeal:       $\mathfrak{i} \triangleleft \mathfrak{g} \; ([\mathfrak{g}, \mathfrak{i}] \subseteq \mathfrak{i})$
    KernelIdeal:    $\ker \phi = \{x \in R_1 \mid \phi(x) = \mathbf{0}_{R_2}\}$
"""

